#!/usr/bin/env python3
"""Generate the revised manuscript's empirical values, tables and vector figures.

Only the revised selected-reference ID outputs supply identification results.
Historical random-label classification results are explicitly separate inputs.
"""
import json
import os
import tempfile
from pathlib import Path

os.environ.setdefault('MPLCONFIGDIR', str(Path(tempfile.gettempdir())/'wid-mpl-config'))
os.environ.setdefault('XDG_CACHE_HOME', str(Path(tempfile.gettempdir())/'wid-font-cache'))

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / 'results/wid_revision_2026-11-08'
OLD = ROOT / 'results/wid_handedness_2026-10-29'
OUT = ROOT / 'paper/figures_revision'
KEY = ['rep', 'query', 'n', 'k']
NAMES = {'stroke':'STROKE','hc183':'HC-183','resnet18':'ResNet-18',
         'efficientnet_b0':'EffNet-B0','vit_b_16':'ViT-B/16','stroke_cnn':'Stroke-CNN'}
COLORS = {'stroke':'#D55E00','hc183':'#0072B2','resnet18':'#009E73',
          'efficientnet_b0':'#E69F00','vit_b_16':'#CC79A7','stroke_cnn':'#555555'}
REPS = list(NAMES)
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':8,'axes.labelsize':8,
                     'xtick.labelsize':8,'ytick.labelsize':8,'legend.fontsize':8,
                     'pdf.fonttype':42,'ps.fonttype':42,'axes.spines.top':False,
                     'axes.spines.right':False,'axes.linewidth':.7,'savefig.facecolor':'white'})


def pct(x, digits=1, signed=False):
    return f'{100*x:+.{digits}f}' if signed else f'{100*x:.{digits}f}'


def tabfile(name, rows, bottom=True):
    text = '% Generated by code/make_revision_paper.py; do not edit.\n'
    text += '\n'.join(rows) + '\n'
    if bottom:
        text += '\\bottomrule\n'
    (OUT/name).write_text(text)


def row(cells):
    return ' & '.join(map(str,cells)) + r' \\'


def save(fig, name):
    fig.savefig(OUT/f'{name}.pdf')
    fig.savefig(OUT/f'{name}.png',dpi=200)
    plt.close(fig)


def panel(ax, letter):
    ax.set_title(f'({letter})',loc='left',fontweight='bold',fontsize=9,pad=6)


def main():
    OUT.mkdir(exist_ok=True)
    S=pd.read_csv(RUN/'id_summary.csv')
    T=pd.read_csv(RUN/'id_paired_tests.csv')
    H=pd.read_csv(RUN/'handedness_accuracy.csv').set_index(['hand_model','n'])
    E=pd.read_csv(RUN/'checks_effect_intervals.csv')
    I=pd.read_csv(RUN/'checks_filter_identity.csv')
    O=pd.read_csv(RUN/'checks_oracle_partitions.csv')
    A=pd.read_csv(RUN/'checks_calibration.csv')
    B=pd.read_csv(RUN/'checks_both_direct_paired_own.csv')
    BO=pd.read_csv(RUN/'checks_both_own_effect.csv').iloc[0]
    U=pd.read_csv(OLD/'features/units.csv')
    L=pd.read_csv(OLD/'leakage_accuracy.csv')
    F=json.loads((RUN/'checks_findings.json').read_text())
    BA=pd.read_csv(RUN/'breakeven_analytic.csv')
    EI=E[E.scope=='all_120_settings'].set_index('contrast')
    M={'Writers':U.writer_id.nunique(),'Left':U[U.label==1].writer_id.nunique(),
       'Images':int((U.n==1).sum()),'Units':len(U),'Invalid':int((~U.valid).sum()),'Settings':120,
       'HandShared':pct(H.loc[('hc183',1),'shared']),'HandOwn':pct(H.loc[('hc183',1),'own']),
       'HandWriter':pct(H.loc[('hc183',1),'writer_all_units']),
       'LawN':len(I),'LawR':f"{F['product_r']:.3f}",'LawMae':pct(F['product_mae']),
       'LawBias':pct(F['product_bias'],signed=True),
       'ThresholdMed':pct(BA[BA['query']=='own'].threshold.median(),0),
       'ThresholdMin':pct(BA[BA['query']=='own'].threshold.min(),0),
       'ThresholdMax':pct(BA[BA['query']=='own'].threshold.max(),0)}
    for label,contrast in [('Known','known_minus_none'),('Fusion','query_bayes_minus_none'),('Filter','query_filter_minus_none')]:
        a=EI.loc[contrast]
        M[label+'Gain']=pct(a.estimate,signed=label!='Known')
        M[label+'Lo']=pct(a.ci_lo,signed=True)
        M[label+'Hi']=pct(a.ci_hi,signed=True)
    le=L[(L.n==1)&(L.part=='own')&(L.regime=='enrolment-trained')]
    M['LeakEn']=pct(le[le.label=='hand'].acc.iloc[0])
    M['LeakRandomMin']=pct(le[le.label=='pseudo'].acc.min())
    M['LeakRandomMax']=pct(le[le.label=='pseudo'].acc.max())
    aa=A[(A.hand_model=='hc183')&(A.n==1)&(A.part=='own')].iloc[0]
    M['BrierOwn']=f'{aa.brier:.3f}';M['NllOwn']=f'{aa.log_loss:.3f}'
    ar=EI.loc['known_hand_minus_random_partition_expectation']
    M['OracleVsRandom']=pct(ar.estimate,signed=True)
    M['OracleVsRandomLo']=pct(ar.ci_lo,signed=True)
    M['OracleVsRandomHi']=pct(ar.ci_hi,signed=True)
    M['RandomKnownGain']=pct(EI.loc['known_random_expected_minus_none'].estimate)
    M['BothGain']=pct(BO.estimate,2,signed=True)
    M['BothLo']=pct(BO.ci_lo,2,signed=True)
    M['BothHi']=pct(BO.ci_hi,2,signed=True)
    ex=I[(I.rep=='hc183')&(I['query']=='own')&(I.n==1)&(I.k==1)&(I.hand_model=='hc183')].iloc[0]
    M['ExampleProduct']=pct(ex.product_approximation);M['ExampleFilter']=pct(ex.filter_top1)
    M['ExampleCondCorrect']=pct(ex.known_success_given_hand_correct);M['ExampleCondWrong']=pct(ex.known_success_given_hand_wrong)
    (OUT/'revision_macros.tex').write_text('% Generated from revised results.\n'+''.join(f'\\newcommand{{\\r{k}}}{{{v}}}\n' for k,v in M.items()))
    (RUN/'manuscript_values.json').write_text(json.dumps(M,indent=2)+'\n')

    def series(scenario,hm,method):
        return S[(S.scenario==scenario)&(S.hand_model==hm)&(S.method==method)].set_index(KEY).top1
    none=series('none','-','none');known=series('oracle','-','filter')
    fusion=series('query','hc183','bayes');filt=series('query','hc183','filter')
    rows=[]
    for rep in REPS:
        cells=[NAMES[rep]]
        for c in [('own',1,1),('own',4,6)]:
            cells.extend(pct(s.loc[(rep,*c)]) for s in (none,known,fusion,filt))
        rows.append(row(cells))
    tabfile('table_main.tex',rows)
    rows=[]
    for t in T[T.primary].sort_values(['n','rep']).itertuples():
        k=(t.rep,t.query,t.n,t.k)
        lab='Paragraph, $k=1$' if t.n==1 else 'Quarter strip, $k=6$'
        cells=[lab,NAMES[t.rep],pct(none.loc[k]),pct(fusion.loc[k]),
               f'{pct(t.diff_top1,signed=True)} [{pct(t.ci_lo,signed=True)}, {pct(t.ci_hi,signed=True)}]',
               f'{t.p_signflip:.3f}',f'{t.p_holm:.3f}']
        rows.append(row(cells))
    tabfile('table_tests.tex',rows)
    rows=[]
    for n in [1,2,4,8]:
        for h in [0,1]:
            for part in ['shared','own']:
                d=U[(U.n==n)&(U.label==h)&((U.para<=6) if part=='shared' else (U.para>=7))]
                rows.append(row([n,'L' if h else 'R',part,len(d),int((~d.valid).sum()),int(d.valid.sum())]))
    tabfile('table_exclusions.tex',rows)
    labels={'known_minus_none':'Known hand vs none','query_bayes_minus_none':'Predicted-query fusion vs none',
            'query_filter_minus_none':'Predicted-query filter vs none',
            'known_random_expected_minus_none':'Expected random partition vs none',
            'known_hand_minus_random_partition_expectation':'Known hand vs expected random partition'}
    rows=[]
    for key,label in labels.items():
        t=EI.loc[key]
        rows.append(row([label,pct(t.estimate,signed=True),f'[{pct(t.ci_lo,signed=True)}, {pct(t.ci_hi,signed=True)}]',f'{t.p_signflip:.4f}']))
    tabfile('table_effects.tex',rows)
    D=pd.read_csv(RUN/'checks_dependence_uncertainty.csv')
    labeld={'all_456':'All combinations','hc183':'HC-183','hc183_adj':'HC-183 adjusted','hc183_writerlevel':'HC-183, linked texts','stroke':'STROKE'}
    rows=[]
    for d in D.itertuples():
        rows.append(row([labeld[d.group],f'{pct(d.bias,signed=True)} [{pct(d.bias_ci_lo,signed=True)}, {pct(d.bias_ci_hi,signed=True)}]',f'{pct(d.mae)} [{pct(d.mae_ci_lo)}, {pct(d.mae_ci_hi)}]',f'{d.pooled_r:.3f} [{d.pooled_r_ci_lo:.3f}, {d.pooled_r_ci_hi:.3f}]']))
    tabfile('table_dependence.tex',rows)
    X=pd.read_csv(RUN/'checks_cross_hand_summary.csv').set_index('rep')
    rows=[]
    for rep in REPS:
        d=X.loc[rep]
        rows.append(row([NAMES[rep],f'{pct(d.cross_hand_share)} [{pct(d.ci_lo)}, {pct(d.ci_hi)}]']))
    tabfile('table_cross_hand.tex',rows)

    rows=[]
    for hm,label in [('hc183','HC-183'),('hc183_adj','HC-183 adjusted'),('stroke','STROKE')]:
        a=A[(A.hand_model==hm)&(A.n==1)&(A.part=='own')].iloc[0]
        rows.append(row([label,f'{pct(a.accuracy)} [{pct(a.accuracy_ci_lo)}, {pct(a.accuracy_ci_hi)}]',
                         f'{a.brier:.3f}',f'{a.log_loss:.3f}']))
    tabfile('table_calibration.tex',rows)
    rows=[]
    labs={'pseudo':'Random labels','pseudo_scaled':'Random labels, scaled','random':'Random directions'}
    for b in B.itertuples():
        rows.append(row([labs[b.control],b.instances,pct(b.control_mean_gain,signed=True),
                         f'{pct(b.estimate,signed=True)} [{pct(b.ci_lo,signed=True)}, {pct(b.ci_hi,signed=True)}]',
                         f'{b.p_control_ge_hand:.3f}']))
    tabfile('table_both.tex',rows)
    rows=[]
    for rep in REPS:
        for query,k in [('shared',5),('own',1),('own',2),('own',3),('own',6)]:
            for n in [1,2,4,8]:
                key=(rep,query,n,k)
                rows.append(row([NAMES[rep],query,n,k]+[pct(s.loc[key]) for s in (none,known,fusion,filt)]+[pct(none.loc[key]/known.loc[key])]))
    tabfile('table_all_settings.tex',rows,bottom=False)

    # Main figure: two difficulty panels and designated paired intervals.
    fig,axes=plt.subplots(1,3,figsize=(7.15,2.5),gridspec_kw={'width_ratios':[1,1,1.05]})
    shown=['stroke','hc183','resnet18','vit_b_16']
    for ax,condition in zip(axes[:2],['query','reference']):
        for rep in shown:
            for ser,style in [(none,'-'),(known,'--'),(fusion,':')]:
                vals=[ser.loc[(rep,'own',n,6)] for n in [1,2,4,8]] if condition=='query' else [ser.loc[(rep,'own',1,k)] for k in [1,2,3,6]]
                ax.plot(range(4),100*np.array(vals),style,color=COLORS[rep],linewidth=1.3,marker='o',markersize=2)
        ax.set_ylim(0,103);ax.set_xticks(range(4))
        ax.grid(axis='y',alpha=.15)
    axes[0].set_xticklabels(['Full','1/2','1/4','1/8']);axes[0].set_xlabel('Query fraction (six references)')
    axes[0].set_ylabel('Top-1 accuracy (%)')
    axes[1].set_xticklabels(['1','2','3','6']);axes[1].set_xlabel('Reference paragraphs (full query)')
    axes[0].legend([Line2D([0],[0],color=COLORS[r],lw=1.5) for r in shown],[NAMES[r] for r in shown],loc='lower left',frameon=False,handlelength=1.3)
    axes[1].legend([Line2D([0],[0],color='black',ls=s) for s in ['-','--',':']],['None','Known','Fusion'],loc='lower right',frameon=False,handlelength=1.5)
    P=T[T.primary].sort_values(['n','rep']).reset_index(drop=True)
    for j,p in P.iterrows():
        axes[2].errorbar(100*p.diff_top1,j,xerr=np.array([[100*(p.diff_top1-p.ci_lo)],[100*(p.ci_hi-p.diff_top1)]]),fmt='o',color=COLORS[p.rep],capsize=2,markersize=3)
    axes[2].set_yticks(range(4),[('R18' if r.rep=='resnet18' else 'ViT')+(' full' if r.n==1 else ' quarter') for r in P.itertuples()])
    axes[2].invert_yaxis();axes[2].axvline(0,color='gray',ls=':',lw=.8)
    axes[2].set_xlabel('Fusion minus none (points)');axes[2].set_xlim(-5,4)
    for ax,l in zip(axes,'abc'):panel(ax,l)
    fig.subplots_adjust(left=.085,right=.985,bottom=.24,top=.87,wspace=.6)
    save(fig,'performance')

    fig,axes=plt.subplots(1,3,figsize=(7.15,2.7),gridspec_kw={'width_ratios':[1.1,1.15,1]})
    hnames={'hc183':'HC-183','hc183_adj':'Adjusted HC-183','stroke':'STROKE','hc183_writerlevel':'HC-183 linked texts'}
    axes[0].scatter(I.product_approximation,I.filter_top1,s=6,color='#0072B2',alpha=.5,edgecolors='none')
    axes[0].plot([0,1],[0,1],color='gray',lw=.8);axes[0].set_xlim(0,1);axes[0].set_ylim(0,1)
    axes[0].set_xlabel('Independence product');axes[0].set_ylabel('Observed filter accuracy')
    axes[0].text(.04,.96,f'n = {len(I)}, r = {F["product_r"]:.3f}',transform=axes[0].transAxes,va='top',fontsize=8)
    axes[1].boxplot([100*I[I.rep==r].covariance.to_numpy() for r in REPS],widths=.55,orientation='horizontal',
                    flierprops={'markersize':2,'markeredgewidth':.4},medianprops={'color':'#0072B2'},whiskerprops={'linewidth':.7})
    axes[1].axvline(0,color='gray',ls=':',lw=.8)
    axes[1].set_yticks(range(1,7),[NAMES[r] for r in REPS])
    axes[1].invert_yaxis();axes[1].set_xlabel('Observed minus product\n(points)')
    oo=O.groupby('rep')[['base','known_hand','random_partition_exact_mean']].mean().reindex(REPS)
    xx=np.arange(1,7)
    axes[2].sharey(axes[1])
    axes[2].barh(xx-.18,100*(oo.known_hand-oo.base),height=.36,color='#0072B2',label='Known hand')
    axes[2].barh(xx+.18,100*(oo.random_partition_exact_mean-oo.base),height=.36,color='#999999',label='Random partition')
    axes[2].tick_params(axis='y',labelleft=False)
    axes[2].set_xlabel('Oracle gain\n(points)');axes[2].set_xlim(0,12)
    handles,labels=axes[2].get_legend_handles_labels()
    fig.legend(handles,labels,frameon=False,fontsize=8,loc='upper right',ncol=2,bbox_to_anchor=(.99,1.02))
    for ax,l in zip(axes,'abc'):panel(ax,l)
    fig.subplots_adjust(left=.07,right=.99,bottom=.25,top=.82,wspace=.82)
    save(fig,'diagnostics')

    RB=pd.read_csv(RUN/'checks_reliability_bins.csv')
    fig,axes=plt.subplots(1,2,figsize=(6.8,2.65),sharex=True,sharey=True)
    for ax,part in zip(axes,['shared','own']):
        b=RB[(RB.hand_model=='hc183')&(RB.n==1)&(RB.part==part)].dropna(subset=['mean_probability','observed_fraction'])
        x=b.mean_probability.to_numpy();y=b.observed_fraction.to_numpy()
        low=np.maximum(0,y-b.fraction_ci_lo.to_numpy());hi=np.maximum(0,b.fraction_ci_hi.to_numpy()-y)
        ax.plot([0,1],[0,1],color='gray',ls=':',lw=.9)
        ax.errorbar(x,y,yerr=[low,hi],fmt='o-',color='#0072B2',lw=1,capsize=3,markersize=4)
        for r in b.itertuples():ax.annotate(str(r.n_units),(r.mean_probability,r.observed_fraction),xytext=(5,3),textcoords='offset points',fontsize=7)
        ax.set_title('Shared paragraphs' if part=='shared' else 'Self-chosen paragraphs',fontsize=9)
        ax.set_xlim(-.03,1.08);ax.set_ylim(-.04,1.08);ax.set_xlabel('Mean predicted left-hand probability')
    axes[0].set_ylabel('Observed left-hand fraction')
    fig.tight_layout(pad=1.4);save(fig,'calibration')

    fig,(scheme,ax)=plt.subplots(1,2,figsize=(6.8,2.85),gridspec_kw={'width_ratios':[1.2,1]})
    from matplotlib.patches import FancyBboxPatch, FancyArrowPatch
    scheme.set_xlim(0,1);scheme.set_ylim(0,1);scheme.axis('off')
    scheme.text(.02,.96,'One fixed random label per writer',fontsize=8.5,va='top')
    for y,title,train,test in [(.63,'Writer held out','Fit: writers B, C','Query: writer A'),
                               (.18,'Writer overlap','Fit: A shared, B, C','Query: A own')]:
        scheme.text(.02,y+.25,title,fontsize=8,fontweight='bold')
        for x,w,text in [(.02,.40,train),(.69,.29,test)]:
            scheme.add_patch(FancyBboxPatch((x,y),w,.18,boxstyle='round,pad=.01',
                edgecolor='#999999',facecolor='#f3f6f8',lw=.7))
            scheme.text(x+w/2,y+.09,text,ha='center',va='center',fontsize=7.8)
        scheme.text(.55,y+.09,'Model',ha='center',va='center',fontsize=8)
        for x0,x1 in [(.43,.48),(.62,.68)]:
            scheme.add_patch(FancyArrowPatch((x0,y+.09),(x1,y+.09),arrowstyle='-|>',mutation_scale=7,lw=.8,color='#666666'))
    scheme.text(.02,.03,'Overlap changes the learning target.',fontsize=8,va='bottom')
    rng=np.random.default_rng(42)
    for j,regime in enumerate(['writer-independent','enrolment-trained']):
        a=L[(L.n==1)&(L.part=='own')&(L.regime==regime)]
        r=a[a.label=='pseudo'].acc.to_numpy()
        ax.scatter(j+rng.uniform(-.12,.12,len(r)),100*r,s=15,color='#777777',alpha=.7,label='Random labels' if j==0 else None)
        ax.scatter([j],[100*a[a.label=='hand'].acc.iloc[0]],s=38,marker='D',color='#D55E00',label='Handedness' if j==0 else None,zorder=4)
    ax.axhline(50,color='gray',ls=':',lw=.8);ax.set_ylim(0,100);ax.set_xlim(-.45,1.45)
    ax.set_xticks([0,1],['Held out','Enrolled']);ax.set_ylabel('Own-paragraph accuracy (%)')
    ax.legend(frameon=False,loc='lower right',fontsize=8)
    panel(scheme,'a');panel(ax,'b');fig.tight_layout(pad=.8,w_pad=1.7);save(fig,'label_controls')

    SIM=pd.read_csv(RUN/'breakeven_simulation.csv.gz')
    sg=SIM[(SIM['query']=='own')&(SIM.n==1)&(SIM.k==1)].groupby(['rep','acc'])[['base','bayes','filter']].mean().reset_index()
    fig,axes=plt.subplots(1,2,figsize=(6.8,2.6))
    for ax,method,title in zip(axes,['bayes','filter'],['Probabilistic fusion','Hard filtering']):
        sg['gain']=sg[method]-sg.base
        pp=sg.groupby('acc').gain.agg(['mean','min','max'])
        ax.fill_between(pp.index,100*pp['min'],100*pp['max'],color='#0072B2',alpha=.15)
        ax.plot(pp.index,100*pp['mean'],color='#0072B2',lw=1.5,marker='o',markersize=2.5)
        ax.axhline(0,color='gray',ls=':',lw=.8);ax.set_title(title,fontsize=9)
        ax.set_xlabel('Target attribute accuracy');ax.set_xlim(.49,1.01)
    axes[0].set_ylabel('Change in top-1 (points)');fig.tight_layout();save(fig,'simulation')
    print('Generated tables, macros and six vector figures in',OUT)


if __name__=='__main__':
    main()
