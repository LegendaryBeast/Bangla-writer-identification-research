#!/usr/bin/env python3
"""Additional numeric macros/tables/figure for nested fusion and robustness."""
import json
import numpy as np
import pandas as pd

from make_revision_paper import ROOT,OUT,NAMES,REPS,COLORS,pct,row,tabfile,save,panel
import matplotlib.pyplot as plt

RUN=ROOT/'results/wid_fusion_robustness_2026-11-08'
BASE=ROOT/'results/wid_revision_2026-11-08'
KEY=['rep','query','n','k']


def ci(r,scale=100,d=2):
    return f'{scale*r.estimate:+.{d}f} [{scale*r.ci_lo:+.{d}f}, {scale*r.ci_hi:+.{d}f}]'


def main():
    E=pd.read_csv(RUN/'nested_effect_intervals.csv')
    N=pd.read_csv(RUN/'nested_paired_tests.csv')
    P=pd.read_csv(RUN/'nested_selected_parameters.csv')
    TS=pd.read_csv(RUN/'temperature_selected_writer.csv')
    SE=pd.read_csv(RUN/'calibration_seed_identification_effects.csv')
    CM=pd.read_csv(RUN/'calibration_seed_metrics.csv')
    V=pd.read_csv(RUN/'calibration_prediction_variability_summary.csv')
    O=pd.read_csv(RUN/'evaluation_writer_omission_summary.csv')
    OM=pd.read_csv(RUN/'evaluation_writer_omission.csv')
    TM=pd.read_csv(RUN/'temperature_multiplier_effects.csv')
    C=pd.read_csv(RUN/'class_specific_identification.csv')
    M={}
    for prefix,contrast in [('Nested','nested_minus_none'),('NestedVsFixed','nested_minus_fixed')]:
        r=E[(E.scope=='all_120_settings')&(E.metric=='top1')&(E.contrast==contrast)].iloc[0]
        for name,col in [('Gain','estimate'),('Lo','ci_lo'),('Hi','ci_hi')]:M[prefix+name]=pct(r[col],2,signed=True)
    nn=E[(E.scope=='all_120_settings')&(E.metric=='nll')&(E.contrast=='nested_minus_none')].iloc[0]
    M['NestedNllGain']=f'{nn.estimate:+.3f}';M['NestedNllLo']=f'{nn.ci_lo:+.3f}';M['NestedNllHi']=f'{nn.ci_hi:+.3f}'
    M['WeightMedian']=f'{P.lam.median():.1f}';M['WeightZero']=pct((P.lam==0).mean())
    M['TempLower']=pct(TS.lower_boundary.mean());M['TempUpper']=pct(TS.upper_boundary.mean())
    M['TempNearMedian']=int(TS.near_optimal_count.median())
    own=CM[(CM.n==1)&(CM.part=='own')]
    M['SeedAccuracyMin']=pct(own.accuracy.min());M['SeedAccuracyMax']=pct(own.accuracy.max())
    va=V[(V.n==1)&(V.part=='own')&(V.metric=='any_disagreement')].iloc[0]
    M['SeedDisagree']=pct(va.estimate)
    fe=SE[(SE.scope=='all_120_settings')&(SE.method=='fixed')]
    M['SeedGainMin']=pct(fe.estimate.min(),2,signed=True);M['SeedGainMax']=pct(fe.estimate.max(),2,signed=True)
    for meth,lab in [('fixed','Fixed'),('nested','Nested'),('known','Known'),('filter','Filter')]:
        r=O[(O.scope=='all_120_settings')&(O.method==meth)&(O.metric=='gain_vs_none')].iloc[0]
        M[lab+'OmitMin']=pct(r.omission_min,2,signed=True);M[lab+'OmitMax']=pct(r.omission_max,2,signed=True)
    scale=TM[(TM.scope=='all_120_settings')&(TM.metric=='gain')]
    M['TempGainMin']=pct(scale.estimate.min(),2,signed=True);M['TempGainMax']=pct(scale.estimate.max(),2,signed=True)
    (OUT/'fusion_robustness_macros.tex').write_text('% Generated by code/make_fusion_robustness_paper.py\n'+''.join(f'\\newcommand{{\\r{k}}}{{{v}}}\n' for k,v in M.items()))
    (RUN/'manuscript_values.json').write_text(json.dumps(M,indent=2)+'\n')

    fixed=pd.read_csv(BASE/'id_paired_tests.csv');fixed=fixed[fixed.primary].set_index(KEY)
    rows=[]
    for n in [1,4]:
        for rep in ['resnet18','vit_b_16']:
            k=1 if n==1 else 6;key=(rep,'own',n,k);f=fixed.loc[key]
            d=N[(N.rep==rep)&(N['query']=='own')&(N.n==n)&(N.k==k)]
            a=d[d.contrast=='nested_minus_none'].iloc[0];b=d[d.contrast=='nested_minus_fixed'].iloc[0]
            ff=f'{pct(f.diff_top1,2,signed=True)} [{pct(f.ci_lo,2,signed=True)}, {pct(f.ci_hi,2,signed=True)}]'
            rows.append(row(['Paragraph, $k=1$' if n==1 else 'Quarter, $k=6$',NAMES[rep],ff,ci(a),ci(b),f'{a.p_holm:.3f}',f'{b.p_holm:.3f}']))
    tabfile('table_nested_designated.tex',rows)
    rows=[]
    for metric,label,scalevalue in [('top1','Top-1 (points)',100),('nll','NLL (nats)',1)]:
        for contrast,label2 in [('nested_minus_none','Nested minus none'),('nested_minus_fixed','Nested minus fixed')]:
            r=E[(E.scope=='all_120_settings')&(E.metric==metric)&(E.contrast==contrast)].iloc[0]
            rows.append(row([label,label2,ci(r,scalevalue,3 if scalevalue==1 else 2),f'{r.p_signflip:.4f}']))
    tabfile('table_nested_effects.tex',rows)
    rows=[]
    for rep in REPS:
        d=P[P.rep==rep];q=d.lam.quantile([.25,.5,.75])
        rows.append(row([NAMES[rep],f'{q.loc[.5]:.1f} [{q.loc[.25]:.1f}, {q.loc[.75]:.1f}]',pct((d.lam==0).mean()),pct((d.lam==1).mean()),f'{d.lam.min():.1f}--{d.lam.max():.1f}']))
    tabfile('table_nested_parameters.tex',rows)
    rows=[]
    for rep in REPS:
        d=TS[TS.rep==rep]
        rows.append(row([NAMES[rep],f'{d["T"].median():.4f}',f'{d["T"].min():.4f}--{d["T"].max():.4f}',pct(d.lower_boundary.mean()),pct(d.upper_boundary.mean()),f'{d.near_optimal_count.median():.0f}']))
    tabfile('table_temperature_diagnostics.tex',rows)
    rows=[]
    for r in own.sort_values('seed').itertuples():
        eff=fe[fe.seed==r.seed].iloc[0]
        rows.append(row([r.seed,f'{pct(r.accuracy)} [{pct(r.accuracy_ci_lo)}, {pct(r.accuracy_ci_hi)}]',f'{r.brier:.3f}',f'{r.nll:.3f}',ci(eff)]))
    tabfile('table_calibration_seeds.tex',rows)
    rows=[]
    for r in scale.sort_values('multiplier').itertuples():
        nll=TM[(TM.scope=='all_120_settings')&(TM.metric=='fused_nll')&(TM.multiplier==r.multiplier)].iloc[0]
        rows.append(row([f'{r.multiplier:g}',ci(r),f'{nll.estimate:.3f} [{nll.ci_lo:.3f}, {nll.ci_hi:.3f}]']))
    tabfile('table_temperature_sensitivity.tex',rows)
    labels={'known':'Known','fixed':'Fixed fusion','nested':'Nested fusion','filter':'Hard filter'}
    rows=[]
    for method in labels:
        d=O[(O.scope=='all_120_settings')&(O.method==method)&(O.metric=='gain_vs_none')].iloc[0]
        rows.append(row([labels[method],pct(d.full_estimate,2,signed=True),f'[{pct(d.omission_min,2,signed=True)}, {pct(d.omission_max,2,signed=True)}]',pct(d.max_absolute_change,2),d.most_influential_writer.replace('_',r'\_')]))
    tabfile('table_writer_influence.tex',rows)
    rows=[]
    for method in labels:
        vals=[]
        for hand in ['left','right']:
            d=C[(C.scope=='all_120_settings')&(C.method==method)&(C.metric=='gain_vs_none')&(C.hand==hand)].iloc[0]
            vals.append(ci(d))
        rows.append(row([labels[method]]+vals))
    tabfile('table_class_effects.tex',rows)

    # Complete same-setting comparison adds nested weights without changing baselines.
    S=pd.read_csv(BASE/'id_summary.csv');NS=pd.read_csv(RUN/'nested_summary.csv')
    def sel(scen,hm,method):return S[(S.scenario==scen)&(S.hand_model==hm)&(S.method==method)].set_index(KEY).top1
    none=sel('none','-','none');known=sel('oracle','-','filter');fixeds=sel('query','hc183','bayes');fil=sel('query','hc183','filter')
    nested=NS[NS.method=='nested'].set_index(KEY).top1
    rows=[]
    for rep in REPS:
        for query,k in [('shared',5),('own',1),('own',2),('own',3),('own',6)]:
            for n in [1,2,4,8]:
                key=(rep,query,n,k)
                rows.append(row([NAMES[rep],query,n,k]+[pct(v.loc[key]) for v in [none,known,fixeds,nested,fil]]+[pct(none.loc[key]/known.loc[key])]))
    tabfile('table_all_settings_nested.tex',rows,bottom=False)

    fig,axes=plt.subplots(2,2,figsize=(6.8,4.0))
    a,b,c,d=axes.ravel()
    short=['STROKE','HC-183','R18','EffNet','ViT','S-CNN']
    a.boxplot([np.log10(TS[TS.rep==r]['T'].to_numpy()) for r in REPS],widths=.55,showfliers=True,flierprops={'markersize':1.5,'alpha':.3},medianprops={'color':'#0072B2'})
    a.set_xticks(range(1,7),short,rotation=25,ha='right');a.set_ylabel('Selected temperature')
    a.set_yticks([-3,-2,-1,0],[r'$10^{-3}$',r'$10^{-2}$',r'$10^{-1}$','1'])
    counts=P.lam.value_counts().sort_index();b.bar(np.arange(len(counts)),counts.to_numpy(),color='#0072B2')
    b.set_xticks(np.arange(len(counts)),[f'{x:g}' for x in counts.index],rotation=45,ha='right');b.set_xlabel('Selected fusion weight');b.set_ylabel('Outer-writer / setting count')
    for j,r in enumerate(fe.sort_values('seed').itertuples()):
        c.errorbar(100*r.estimate,j,xerr=[[100*(r.estimate-r.ci_lo)],[100*(r.ci_hi-r.estimate)]],fmt='o',color='#0072B2',capsize=2,markersize=3)
    c.set_yticks(range(4),[str(x) for x in sorted(fe.seed)]);c.invert_yaxis();c.axvline(0,color='gray',ls=':',lw=.8)
    c.set_xlabel('Fixed fusion minus none (points)');c.set_ylabel('Calibration-fold seed')
    rng=np.random.default_rng(2026)
    for j,(meth,label) in enumerate(labels.items()):
        z=OM[(OM.scope=='all_120_settings')&(OM.method==meth)&(OM.metric=='gain_vs_none')]
        d.scatter(j+rng.uniform(-.13,.13,len(z)),100*z.change_from_full,s=8,color=['#009E73','#0072B2','#CC79A7','#D55E00'][j],alpha=.65,edgecolors='none')
    d.axhline(0,color='gray',ls=':',lw=.8);d.set_xticks(range(4),['Known','Fixed','Nested','Filter']);d.set_ylabel('Omission change in gain (points)')
    for ax,letter in zip(axes.ravel(),'abcd'):panel(ax,letter)
    fig.tight_layout(pad=1.4,h_pad=1.8,w_pad=2.2);save(fig,'fusion_robustness')
    print('Generated nested-fusion and robustness assets.')


if __name__=='__main__':main()
